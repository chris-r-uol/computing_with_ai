"""Audit the vendored data against the registry, and generate ``data/README.md``.

Every file under ``data/`` must be accounted for in ``cwai.registry`` so that the
repository can be published under its open licences with a clear conscience.

Usage:
    uv run python scripts/check_licences.py                 # audit data/
    uv run python scripts/check_licences.py --write-readme  # regenerate README
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

from cwai import registry

BUDGET_MB = 80
BUDGET_BYTES = BUDGET_MB * 1024 * 1024
GENERATED = "generated"
LICENCES_DIR = "LICENSES"
README = "README.md"
ATTRIBUTION_FILE = "ATTRIBUTION.txt"
# ODbL requires the credit to travel with the data, so builders write it beside
# each output. It is accepted only there, and only with the registry's wording.
ATTRIBUTION_LICENCE = "ODbL-1.0"


def _is_documentation(relpath: Path) -> bool:
    return relpath == Path(README) or relpath.parts[0] == LICENCES_DIR


def audit(data_dir: Path) -> list[str]:
    """Return human-readable problems with ``data_dir``; empty when it is clean.

    Every registered dataset must be present: all eight are vendored, so a
    missing file means a broken checkout or a registry entry nothing builds.
    """
    problems: list[str] = []
    datasets = registry.list_datasets()

    claims = Counter(info.relpath for info in datasets)
    for relpath, count in claims.items():
        if count > 1:
            problems.append(
                f"{relpath} is registered {count} times in src/cwai/registry.py; "
                "give each dataset its own file."
            )

    # Directory -> attribution strings of the ODbL outputs registered there.
    notices: dict[Path, set[str]] = {}
    for info in datasets:
        if info.licence == ATTRIBUTION_LICENCE:
            notices.setdefault(Path(info.relpath).parent, set()).add(info.attribution)

    present = [p for p in sorted(data_dir.rglob("*")) if p.is_file()]
    for path in present:
        rel = path.relative_to(data_dir)
        if _is_documentation(rel):
            continue
        if rel.name == ATTRIBUTION_FILE and rel.parent in notices:
            expected = notices[rel.parent]
            if (
                len(expected) != 1
                or path.read_text(encoding="utf-8").strip() not in expected
            ):
                problems.append(
                    f"data/{rel.as_posix()} must contain exactly the attribution "
                    "registered in src/cwai/registry.py for the data beside it. "
                    "Rebuild the dataset or fix the registry; datasets sharing a "
                    "directory must share one attribution string."
                )
            continue
        if rel.as_posix() not in claims:
            problems.append(
                f"data/{rel.as_posix()} is not registered in src/cwai/registry.py. "
                "Register it with its licence and attribution, or delete it."
            )

    for info in datasets:
        if not (data_dir / info.relpath).is_file():
            problems.append(
                f"data/{info.relpath} is missing (dataset '{info.key}'). "
                "Run the script that builds it, or fix the registry entry."
            )

    for licence in sorted({i.licence for i in datasets} - {GENERATED}):
        text = data_dir / LICENCES_DIR / f"{licence}.txt"
        if not text.is_file() or text.stat().st_size == 0:
            problems.append(
                f"data/{LICENCES_DIR}/{licence}.txt is missing or empty, but "
                f"{licence} data is vendored. Add the licence text."
            )

    total = sum(p.stat().st_size for p in present)
    if total >= BUDGET_BYTES:
        problems.append(
            f"data/ is {total / 1024 / 1024:.1f} MB, over the {BUDGET_MB} MB "
            "budget. Subset or compress the data."
        )
    return problems


_INTRO = """\
# Data

This directory holds every dataset used by the module. Do not edit this file by
hand: it is generated from `src/cwai/registry.py` by
`uv run python scripts/check_licences.py --write-readme`, and CI fails if the two
disagree.

## Why licence hygiene matters

Transport research runs on other people's data: police collision records,
government traffic counts, crowd-sourced maps. Each comes with conditions. Most
require you to credit the source in exactly the words the owner specifies, and
the OpenStreetMap licence also requires that anything you build from it stays
open under the same terms. Breaking those conditions can invalidate your right
to use the data at all, and a published result you cannot lawfully share cannot
be reproduced.

So before data enters this repository it is recorded in the registry with its
source, licence and attribution, and `scripts/check_licences.py` checks that
every file here is accounted for, that the licence texts are present in
`LICENSES/`, and that the total stays under {budget} MB. Make the same habit part
of your own projects: record where data came from and what you may do with it
the day you download it, not the day you publish.

## Datasets
"""


def readme_text() -> str:
    """Render ``data/README.md`` from the registry."""
    parts = [_INTRO.format(budget=BUDGET_MB)]
    for info in registry.list_datasets():
        parts.append(
            f"\n### {info.title}\n\n"
            f"{info.description}\n\n"
            f"- File: `{info.relpath}`\n"
            f"- Licence: {info.licence}\n"
            f"- Source: {info.source_url}\n"
            f"- Attribution: {info.attribution}\n"
        )
    return "".join(parts)


def write_readme(data_dir: Path) -> None:
    """Write the generated README into ``data_dir``."""
    data_dir.mkdir(parents=True, exist_ok=True)
    (data_dir / README).write_text(readme_text(), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    root = registry.data_root()
    if "--write-readme" in args:
        write_readme(root)
        print(f"Wrote {root / README}")
        return 0
    problems = audit(root)
    for problem in problems:
        print(f"PROBLEM: {problem}", file=sys.stderr)
    if problems:
        return 1
    print("Licence audit passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
